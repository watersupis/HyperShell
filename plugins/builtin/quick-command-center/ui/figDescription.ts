export function localizeFigDescription(
  description: string | undefined,
  locale: string,
): string | undefined {
  if (!description) return undefined;
  if (locale !== "zh-CN") return description;

  const normalized = description.trim().replace(/[.!]+$/, "").toLowerCase();
  return chineseDescriptions[normalized] ?? description;
}
